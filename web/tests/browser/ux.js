async (page) => {
  const origin = new URL(page.url()).origin;
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  const tab = (name) => page.getByRole("button", { name, exact: true }).click();
  const active = () => page.evaluate(() => JSON.parse(localStorage.getItem("cauce-workspace-v1")).active);
  const live = () => page.locator('.studio-out[data-origin="en vivo"]').waitFor({ timeout: 65000 });
  const shot = async (name) => {
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({ path: `.playwright-cli/ux-${name}.png`, fullPage: true, animations: "disabled" });
  };
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(origin + "/estudio?vista=ast");
  await page.waitForURL("**/studio?vista=ast");
  await page.locator(".cm-content").waitFor();
  await tab("Compile");
  await live();
  await page.getByLabel("Pipeline del AST").waitFor();
  const before = await active();
  await page.evaluate(() => {
    window.__uxEditor = document.querySelector(".cm-editor");
    window.__uxPosts = 0;
    const post = Worker.prototype.postMessage;
    Worker.prototype.postMessage = function (...args) { window.__uxPosts++; return post.apply(this, args); };
  });
  const step = page.getByRole("button", { name: "Inspeccionar Step · pagados", exact: true });
  await step.hover();
  await page.locator(".cm-source-preview").first().waitFor();
  check((await page.locator(".cm-source-preview").allTextContents()).join("").includes("STEP pagados"), "Hover no muestra la procedencia del STEP");
  check((await active()).revision === before.revision, "Hover creó una revisión");
  await shot("ast-desktop-light");
  await step.focus();
  await page.keyboard.press("Enter");
  check((await page.evaluate(() => window.getSelection().toString())).startsWith("STEP pagados"), "El nodo no seleccionó el STEP exacto");
  await tab("Parse tree");
  await page.locator(".tree-node").first().waitFor();
  const nodeCount = await page.locator(".tree-node").count();
  await page.locator('.tree-toggle[aria-expanded="false"]').first().click();
  check((await page.locator(".tree-node").count()) > nodeCount, "La rama no se expandió");
  await page.getByRole("button", { name: "Alejar grafo" }).click();
  check((await page.getByLabel("Zoom del grafo").innerText()).includes("85"), "Zoom no aplicado");
  await page.getByRole("button", { name: "Ajustar", exact: true }).click();
  await shot("parse-tree-desktop-light");
  await tab("Tokens");
  await page.getByLabel("Buscar token").fill("pagados");
  check((await page.locator(".tokens-table tbody tr").count()) === 2, "Filtro de tokens perdió el orden original o los lexemas");
  await page.locator(".tokens-table tbody .source-button").first().click();
  check((await page.evaluate(() => window.getSelection().toString())) === "pagados", "Token sin rango exacto");
  await page.getByLabel("Buscar token").fill("inexistente-xyz");
  check((await page.locator(".tokens-table tbody tr").count()) === 0, "Búsqueda vacía inventó tokens");
  await page.getByLabel("Buscar token").fill("");
  await shot("tokens-desktop-light");
  await tab("IR");
  await page.locator(".ir-diff").first().waitFor();
  check((await page.locator('.diff-cell[data-change="remove"]').count()) > 0, "IR sin líneas retiradas");
  check((await page.locator('.diff-cell[data-change="add"]').count()) > 0, "IR sin líneas añadidas");
  await page.getByLabel("Solo nodos con cambios").check();
  check((await page.locator('.ir-row[data-change="conservado"]').count()) === 0, "Filtro IR muestra nodos conservados");
  await shot("ir-desktop-light");
  check(await page.evaluate(() => window.__uxPosts === 0 && window.__uxEditor === document.querySelector(".cm-editor")), "Explorar causó recompilación o recreó CodeMirror");
  await page.getByLabel("Pases de optimización").selectOption("O0");
  await live();
  check((await page.locator('.diff-cell[data-change="remove"], .diff-cell[data-change="add"]').count()) === 0, "O0 inventó cambios");
  await page.getByLabel("Solo nodos con cambios").uncheck();
  await page.getByLabel("Pases de optimización").selectOption("default");
  await live();
  await tab("Blocks");
  await page.getByRole("heading", { name: "Construye un pipeline por bloques" }).waitFor();
  const beforeExamples = await active();
  const exampleSelector = page.getByRole("combobox", { name: "Ejemplos de Blocks", exact: true });
  check((await exampleSelector.locator("option").count()) === 7, "Faltan ejemplos en Blocks");
  check(await page.getByRole("button", { name: "Cargar ejemplo", exact: true }).isDisabled(), "Se puede cargar sin elegir un ejemplo");
  const pipelineName = page.getByRole("textbox", { name: "Nombre del pipeline", exact: true });
  await pipelineName.fill("borrador_personal");
  const personalDraft = await page.locator(".blocks-code").innerText();
  await exampleSelector.selectOption("gasto-por-cliente");
  check((await page.locator(".blocks-code").innerText()) === personalDraft, "Elegir un ejemplo sustituyó los bloques antes de cargarlo");
  await page.getByRole("button", { name: "Cargar ejemplo", exact: true }).click();
  check((await pipelineName.inputValue()) === "gasto_por_cliente", "No cargó el pipeline del ejemplo");
  check((await page.locator(".block-transform").count()) === 3, "No cargó todas las transformaciones del ejemplo");
  check((await page.locator(".blocks-errors").count()) === 0, "Ejemplo cargado con referencias inválidas");
  check(JSON.stringify(await active()) === JSON.stringify(beforeExamples), "Cargar el ejemplo modificó el documento de Code");
  await page.getByRole("button", { name: "Restaurar bloques anteriores", exact: true }).click();
  check((await pipelineName.inputValue()) === "borrador_personal" && (await page.locator(".blocks-code").innerText()) === personalDraft, "No restauró el borrador exacto de Blocks");
  await pipelineName.fill("mi_pipeline");
  await page.getByRole("button", { name: "+ Agrupar y resumir", exact: true }).click();
  const aggregate = page.getByRole("region", { name: "Bloque 2: Agrupar y resumir", exact: true });
  await aggregate.getByRole("combobox", { name: "Columna", exact: true }).selectOption("importe");
  await aggregate.getByLabel("Agrupar por").selectOption("cliente");
  await page.getByRole("button", { name: "+ Ordenar filas", exact: true }).click();
  await page.getByRole("region", { name: "Bloque 3: Ordenar filas", exact: true }).getByRole("combobox", { name: "Columna", exact: true }).selectOption("total");
  await page.getByRole("button", { name: "Subir bloque 3" }).click();
  check(await page.getByRole("button", { name: "Abrir como copia en Code" }).isDisabled(), "Referencia rota al reordenar aceptada");
  await page.getByRole("button", { name: "Bajar bloque 2" }).click();
  check(await page.getByRole("button", { name: "Abrir como copia en Code" }).isEnabled(), "No recuperó al corregir el orden");
  await shot("blocks-desktop-light");
  for (const theme of ["light", "dark"]) {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate((theme) => { document.documentElement.dataset.theme = theme; localStorage.setItem("cauce-theme", theme); }, theme);
    check(!(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)), "Blocks desborda en móvil");
    await shot(`blocks-mobile-${theme}`);
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  const previous = await active();
  await page.getByRole("button", { name: "Abrir como copia en Code" }).click();
  await live();
  const generated = await active();
  check(generated.id !== previous.id && generated.name === "mi_pipeline.etl", "Blocks no creó una copia nueva");
  check(await page.evaluate((previous) => JSON.parse(localStorage.getItem("cauce-workspace-v1")).drafts.some((d) => JSON.stringify(d) === JSON.stringify(previous)), previous), "Blocks alteró el documento anterior");
  check((await page.locator(".diagnostic-link").count()) === 0, "DSL generado rechazado por el compilador");
  await page.getByLabel("Dataset para mi_pipeline.datos", { exact: true }).selectOption("join-orders@1");
  await page.getByRole("button", { name: "Run", exact: true }).click();
  await page.locator('.execution-job[data-state="succeeded"]').waitFor({ timeout: 25000 });
  const rows = await page.locator(".execution-results tbody").first().locator("tr").allTextContents();
  check(rows.length === 2 && rows.some((r) => r.includes("70")) && rows.some((r) => r.includes("10")), "El pipeline de Blocks no produjo los totales esperados");
  const [download] = await Promise.all([page.waitForEvent("download"), page.getByRole("link", { name: /Descargar resultado\.csv/ }).click()]);
  await download.saveAs(".playwright-cli/ux-blocks-result.csv");
  await tab("AST");
  await page.getByLabel("Pipeline del AST").waitFor();
  await shot("ast-desktop-dark");
  await page.setViewportSize({ width: 390, height: 844 });
  await tab("Inspector");
  for (const name of ["AST", "Parse tree", "Flow", "IR", "Tokens"]) {
    await tab(name);
    await page.locator(".structured-inspector h2").waitFor();
    check(!(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)), `${name} desborda en móvil`);
    await shot(`${name.toLowerCase().replaceAll(" ", "-")}-mobile-dark`);
  }
  check(errors.length === 0, errors.join("\n"));
  return { ux: true, graph: true, sourceHover: true, noRecompileOnExplore: true, tokenFilter: true, diff: true, O0: true, blocks: true, blockExamples: true, execution: true, download: true, legacyRoute: true, mobile: true, pageErrors: errors };
};
