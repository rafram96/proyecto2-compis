async (page) => {
  const origin = new URL(page.url()).origin;
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const check = (value, message) => { if (!value) throw new Error(message); };
  const frames = () => page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const overflow = () => page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.goto(origin + "/");
  const stack = page.getByRole("region", { name: "Construido sobre", exact: true });
  await stack.scrollIntoViewIfNeeded();
  await page.locator('.technology-viewport[data-running="true"]').waitFor();
  await page.mouse.move(5, 5);
  check(await page.locator(".technology-track").evaluate((el) => getComputedStyle(el).animationPlayState === "running"), "El carrusel no inició");
  const animation = () => page.locator(".technology-track").evaluate((el) => el.getAnimations()[0]?.currentTime ?? 0);
  const start = await animation();
  await page.waitForTimeout(120);
  check((await animation()) > start, "La franja no se desplaza");
  await page.getByRole("button", { name: "Pausar movimiento", exact: true }).click();
  const pausedAt = await animation();
  await page.waitForTimeout(120);
  check(Math.abs((await animation()) - pausedAt) < 30, "La pausa no conserva la posición");
  await page.getByRole("button", { name: "Reanudar movimiento", exact: true }).click();
  await page.locator(".technology-viewport").hover();
  check(await page.locator(".technology-track").evaluate((el) => getComputedStyle(el).animationPlayState === "paused"), "El hover no pausa la franja");
  await page.getByRole("button", { name: "Ver todo el stack", exact: true }).click();
  check((await stack.getByRole("listitem").count()) === 12, "El stack accesible contiene duplicados o faltan tecnologías");
  const assets = stack.locator('.technology-list:not([aria-hidden]) img:visible');
  await assets.evaluateAll((images) => Promise.all(images.map((image) => image.decode())));
  check(await assets.evaluateAll((images) => images.every((image) => image.naturalWidth > 0)), "Logo no disponible");
  await stack.screenshot({ path: ".playwright-cli/home-stack-desktop-light.png", animations: "disabled" });
  await page.getByRole("button", { name: "Volver al carrusel", exact: true }).click();
  await page.emulateMedia({ reducedMotion: "reduce" });
  await frames();
  check(await page.locator(".technology-track").evaluate((el) => getComputedStyle(el).animationName === "none"), "Movimiento reducido mantiene el carrusel");
  check(!(await page.getByRole("button", { name: "Pausar movimiento", exact: true }).count()), "Se ofrece pausar una vista estática");
  for (const [width, height] of [[1440, 1000], [768, 1024], [390, 844], [320, 568], [768, 600]]) {
    await page.setViewportSize({ width, height });
    await page.evaluate(() => scrollTo({ top: 0, behavior: "instant" }));
    await frames();
    check(!(await overflow()), `El inicio desborda a ${width}×${height}`);
    const geometry = await page.evaluate(() => {
      const title = document.querySelector(".half.right").getBoundingClientRect();
      const copy = document.querySelector(".hero-foot").getBoundingClientRect();
      return { titleBottom: title.bottom, copyTop: copy.top };
    });
    check(geometry.copyTop >= geometry.titleBottom, `El texto pisa el titular a ${width}×${height}`);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => localStorage.setItem("cauce-theme", "dark"));
  await page.reload();
  await stack.scrollIntoViewIfNeeded();
  const darkAssets = stack.locator('.technology-list:not([aria-hidden]) img:visible');
  await darkAssets.evaluateAll((images) => Promise.all(images.map((image) => image.decode())));
  check(!(await overflow()), "El stack móvil desborda");
  await stack.screenshot({ path: ".playwright-cli/home-stack-mobile-dark.png", animations: "disabled" });
  await page.locator(".hero-actions").getByRole("link", { name: "Empezar con Blocks", exact: true }).click();
  await page.waitForURL("**/studio#blocks");
  await page.getByRole("heading", { name: "Construye un pipeline por bloques" }).waitFor();
  check((await page.getByRole("button", { name: "Blocks", exact: true }).getAttribute("aria-pressed")) === "true", "El enlace no abrió Blocks");
  const documentBefore = await page.evaluate(() => localStorage.getItem("cauce-workspace-v1"));
  await page.reload();
  await page.getByRole("heading", { name: "Construye un pipeline por bloques" }).waitFor();
  check((await page.evaluate(() => localStorage.getItem("cauce-workspace-v1"))) === documentBefore, "El enlace de Blocks modificó el documento");
  await page.getByRole("button", { name: "Code", exact: true }).click();
  check((await page.evaluate(() => location.hash)) === "", "Code conservó un hash que vuelve a abrir Blocks");
  await page.goBack();
  await page.waitForURL(origin + "/");
  check(errors.length === 0, errors.join("\n"));
  return { landing: true, logos: 12, pause: true, reducedMotion: true, viewports: 5, blocksLink: true, pageErrors: errors };
};
